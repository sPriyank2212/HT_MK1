from common import *


def _crc_examples():
    from core.packet_codec import encode_packet
    out = []
    for name, cmd in (("PING", 1), ("GET_STATUS", 2), ("START_CONT", 5), ("ABORT", 8)):
        out.append([name, f"0x{cmd:02X}", encode_packet(cmd).hex(" ").upper()])
    return out


def build(path):
    d = new_doc("HT_MK0_CWT", "Code Walkthrough")
    d.standard_intro(
        purpose=[
            "This document explains how the HT_MK0 firmware and the Harness "
            "Tester GUI are built: the files, the main routines, the serial "
            "protocol between them, how to build and test them, and the "
            "limitations that a maintainer must know before changing them.",
        ],
        audience=[
            "Engineers who maintain or extend the firmware (C, STM32 HAL) or "
            "the GUI (Python, PyQt6). Familiarity with both languages and with "
            "serial protocols is assumed.",
        ],
        related=PACKAGE_DOCS)

    # ── 2 Architecture ─────────────────────────────────────────────────────────────────────────
    d.h1("Architecture", page_break=True)
    d.p("The system has two programs that talk over a serial link. The "
        "firmware runs on the NUCLEO-F303ZE and owns the 74 test pins. The GUI "
        "runs on the PC, owns everything about netlists, connectors, results "
        "and reports, and drives the firmware with a small binary protocol. "
        "The firmware knows channel numbers only; connector names exist only "
        "in the GUI.")
    d.figure(dia("architecture.png"), "Software architecture", 15.0)
    d.h2("Design Decisions")
    d.bullets([
        "**One side holds the logic.** The firmware performs scans and "
        "reports every pair; the GUI decides what a pair means (pass, fail) "
        "from the netlist and the results.",
        "**Channels, not pins.** The only numbers on the wire are channels 1 "
        "to 37. The mapping to connectors is in an Excel file edited in the "
        "GUI, so the connector layout can change without new firmware.",
        "**Synchronous scans.** The firmware runs a scan to completion inside "
        "the command handler. This keeps timing simple (section 8).",
        "**No resistance or high voltage.** The protocol keeps the commands "
        "for these so that a later board can use the same GUI.",
    ])

    # ── 3 Firmware ─────────────────────────────────────────────────────────────────────────────────────
    d.h1("Firmware")
    d.h2("Source Files")
    d.table(["File", "Role"], [
        ["`Core/Src/main.c`", "Start-up code generated by STM32CubeMX: clocks (72 MHz from the 8 MHz ST-Link clock, PLL x9), RTC, GPIO and USART3; the main loop; the UART receive callbacks."],
        ["`Core/Src/harness.c`", "All test logic: ring buffer, packet decoder and encoder, command handlers, netlist parser, scan routines, LED and button logic."],
        ["`Core/Inc/harness.h`", "Version, protocol constants, command and response codes, state enumeration, public functions."],
        ["`POC_HT.ioc`", "STM32CubeMX project: clock tree, USART3 on PD8 and PD9 at 115200 baud, pin assignments."],
    ], "Firmware source files", weights=[26, 74])
    d.h2("Start-up and Main Loop")
    d.p("main() initialises the HAL, the clock and the peripherals, then "
        "calls HT_Init(). HT_Init() prints a boot line, configures the 74 test "
        "pins, loads the default straight netlist, starts the LED boot "
        "sequence, and sets the state to IDLE. The first receive interrupt is "
        "armed, and the main loop calls HT_Process() forever.")
    d.p("The USART3 receive interrupt delivers one byte at a time to "
        "HT_UART_RxByte(), which stores it in a 512-byte ring buffer. A byte "
        "is dropped if the buffer is full. HT_Process() empties the buffer "
        "through the packet decoder, runs a button request if one is pending, "
        "and updates the LEDs.")
    d.h2("Test Pins")
    d.p("Side A pins are push-pull outputs, initialised LOW. Side B pins are "
        "inputs with the internal pull-down. The two tables SIDE_A and SIDE_B "
        "in harness.c list the port and pin of each channel; the GUI's "
        "default connector configuration repeats them as notes and is "
        "checked against them when this document is built.")
    d.p("Pins reserved by the board (the LEDs PB0, PB7 and PB14, the user "
        "button PC13, the serial pins PD8 and PD9, and the debug pins PA13 and "
        "PA14) are not used. Section 7 lists the channels whose pin also has "
        "another function.")
    d.h3("Releasing the Trace Pins")
    d.p("Five Side-B pins, PE2 to PE6, belong to the debug trace port while "
        "the DBGMCU_CR register has the TRACE_IOEN bit set. That register is "
        "cleared only by a power-on reset, so one debug session can leave the "
        "pins driven for every later reset and re-flash. release_trace_pins() "
        "clears the bit. It runs at start-up and again at the beginning of "
        "every scan, because a debugger can attach afterwards. The state of "
        "the bit is reported in the flags byte of the status reply.")
    d.h2("State Machine")
    d.figure(dia("state_machine.png"), "Firmware state machine", 14.5)
    d.p("The states are IDLE, UPLOADING, CALIBRATING, SCANNING, HV_TESTING, "
        "COMPLETE and FAULT, numbered 0 to 6 in the status reply. The "
        "firmware enters SCANNING for every test and AUTO_SCAN. The "
        "HV_TESTING state is used by the simulated insulation command only. "
        "FAULT has an LED pattern but nothing in this version enters it.")
    d.h2("Scan Routines")
    d.p("All scans start with the same two steps: release the trace pins, "
        "then a baseline check. The baseline check drives every Side-A pin "
        "LOW, waits 10 ms, and reads all Side-B pins. Any input that reads "
        "HIGH is stuck, and a fault packet names up to four of them. A stuck "
        "input would look connected to every pin, so it is reported before it "
        "can cause a false pass.")
    d.table(["Scan", "Command", "Pairs", "What is sent"], [
        ["Continuity", "START_CONT (0x05)", "Those in the netlist, in list order",
         "One RESULT_CONT per pair: PASS or OPEN"],
        ["Cross continuity", "START_CROSS_CONT (0x0C)", "All 37 by 37",
         "One RESULT_CONT per pair: PASS, OPEN, MISWIRE or NOT_CONNECTED"],
        ["Auto-Scan", "AUTO_SCAN (0x0B)", "All 37 by 37",
         "RESULT_CONT (PASS) only for pairs found, skipping stuck inputs"],
        ["Short-circuit", "START_SHORT (0x06)", "All 37 by 37",
         "RESULT_SHORT for unexpected pairs; not used by the GUI"],
        ["Insulation", "START_HV (0x07)", "Those in the netlist",
         "Fixed simulated values; not used by the GUI"],
    ], "Scan routines", weights=[20, 26, 24, 30])
    d.p("The continuity loop for one pair is:")
    d.code([
        "drive Side A pin a HIGH",
        "wait 5 ms",
        "high = read Side B pin b",
        "drive Side A pin a LOW",
        "status = high ? PASS : OPEN",
        "send RESULT_CONT(a, b, resistance, status)",
    ])
    d.p("Cross continuity and Auto-Scan drive each Side-A pin once and read all "
        "Side-B pins, so they take 37 settling delays rather than one per "
        "pair. Progress packets are sent after every fourth Side-A pin or "
        "pair. After the last pair the firmware releases all pins, sends "
        "SCAN_DONE with the totals, remembers pass or fail for the LEDs, "
        "and enters COMPLETE.")
    d.h2("Netlist Handling")
    d.p("The GUI sends the netlist as compact JSON in chunks. The firmware "
        "collects the chunks, and when all have arrived it scans the text for "
        "each \"pins\" array and reads the \"n\" values in it. Every "
        "combination of two pins in a net, in list order, becomes an expected "
        "pair. It does not parse names or other fields.")
    d.table(["Limit", "Value"], [
        ["Netlist text", "4096 bytes"],
        ["Chunks", "64"],
        ["Expected pairs", "256"],
        ["Pins in one net", "64"],
        ["Pin numbers", "1 to 255 accepted; 37 are real"],
    ], "Netlist limits in the firmware", weights=[50, 50])
    d.p("With no netlist uploaded, or after a reset, the firmware uses the "
        "default straight map A1-B1 to A37-B37. A netlist stays in memory "
        "until the next upload or a reset.")
    d.h2("LEDs and Button")
    d.p("led_update() runs on every pass of HT_Process() and inside the scan "
        "loops. It sets the LEDs from the state: the boot blink for 1.2 s, "
        "steady green at idle, a blue blink while uploading or scanning "
        "(250 ms) or calibrating (100 ms), and two 100 ms blinks, green or "
        "red, at the end of a run. The user button, on interrupt EXTI15_10, "
        "sets a flag; HT_Process() then runs an Auto-Scan if the tester is idle.")

    # ── 4 Protocol ─────────────────────────────────────────────────────────────────────────────────────────
    d.h1("Serial Protocol")
    d.p("The link is USART3 on PD8 and PD9, bridged by the ST-Link to a "
        "virtual COM port, at 115200 baud, 8 data bits, no parity, 1 stop bit. "
        "All multi-byte numbers are big-endian.")
    d.figure(dia("packet_frame.png"), "Serial packet frame", 14.5)
    d.p("The length byte counts the payload only; the frame has "
        "five bytes of overhead. The CRC is CRC-16/CCITT-FALSE (polynomial "
        "0x1021, initial value 0xFFFF, no reflection, no final XOR) over the "
        "command byte and the payload. The firmware discards a packet whose "
        "CRC is wrong without answering; the GUI logs a CRC error and carries "
        "on. Example frames made by the GUI's own encoder:")
    d.table(["Command", "Code", "Frame (hexadecimal)"], _crc_examples(),
            "Example frames", weights=[26, 14, 60])
    d.h2("Commands, PC to Tester")
    d.table(["Code", "Name", "Payload", "Reply"], [
        ["0x01", "PING", "none", "ACK"],
        ["0x02", "GET_STATUS", "none", "STATUS"],
        ["0x03", "SET_NETLIST", "chunk number (2), chunk count (2), up to 250 bytes of JSON", "ACK"],
        ["0x04", "SET_PARAM", "three 16-bit values: R limit, IR limit, HV soak", "ACK"],
        ["0x05", "START_CONT", "none", "ACK, then results"],
        ["0x06", "START_SHORT", "none", "ACK, then results"],
        ["0x07", "START_HV", "none", "ACK, then simulated results"],
        ["0x08", "ABORT", "none", "ACK"],
        ["0x09", "CALIBRATE", "none", "ACK with a 16-bit offset (idle only)"],
        ["0x0A", "GET_RESULT", "none", "STATUS (results are not stored)"],
        ["0x0B", "AUTO_SCAN", "none", "ACK, then results"],
        ["0x0C", "START_CROSS_CONT", "none", "ACK, then results"],
    ], "Commands", center_cols=(0,), weights=[11, 24, 43, 22])
    d.p("A start command is accepted only in IDLE or COMPLETE; otherwise the "
        "reply is NACK. An unknown command is answered with NACK.")
    d.h2("Responses, Tester to PC")
    d.table(["Code", "Name", "Payload"], [
        ["0x81", "ACK", "none, or the 16-bit calibration offset"],
        ["0x82", "NACK", "none"],
        ["0x83", "STATUS", "state, flags, firmware major, minor, patch, calibration offset (2), pad"],
        ["0x84", "RESULT_CONT", "pin A, pin B, resistance (4, in 0.1 milliohm), status"],
        ["0x85", "RESULT_SHORT", "pin A, pin B, short flag"],
        ["0x86", "RESULT_HV", "pin A, pin B, insulation (4), voltage (2), fail flag"],
        ["0x87", "SCAN_DONE", "total (2), passed (2), failed (2)"],
        ["0x88", "PROGRESS", "done (2), total (2)"],
        ["0x89", "FAULT", "code (1), data (4)"],
    ], "Responses", center_cols=(0,), weights=[11, 24, 65])
    d.p("**RESULT_CONT status:** 0 pass, 1 open (expected pair missing), 2 "
        "miswire (unexpected pair present), 3 not connected (none expected, "
        "none found). **STATUS flags:** bit 0, the trace port was enabled when "
        "the firmware started; bit 1, the firmware was built to keep trace. "
        "**FAULT code 1:** stuck inputs; the data field holds the first four "
        "pin numbers, one per byte, most significant first, zero if unused. "
        "The resistance field carries a fixed placeholder, 50 milliohm for a "
        "found pair and 50 ohm for a missing one.")
    d.figure(dia("sequence.png"), "Message sequence of a Continuity test", 14.0)
    d.p("The GUI sends a PING every two seconds while idle. If three pings in "
        "a row get no ACK, it closes the port and reports a lost connection.")

    # ── 5 GUI ────────────────────────────────────────────────────────────────────────────────────────────────
    d.h1("Harness Tester GUI")
    d.h2("Module Overview")
    d.table(["Module", "Role"], [
        ["`main.py`", "Creates the application, seeds the data folder and shows the main window maximised."],
        ["`ui/main_window.py`", "The window: menus, tabs, and the handlers that join the engine, the worker and the views."],
        ["`ui/left_panel.py`", "Connection, netlist and profile groups; port scan; profile files."],
        ["`ui/test_control_bar.py`", "Mode box, START and STOP, progress, duration, verdict."],
        ["`ui/connector_view.py`", "The connector diagrams: Single view canvas and Sections view."],
        ["`ui/matrix_view.py`", "Pin states and their colours and names."],
        ["`ui/results_table.py`", "Results table, filters, sorting, context menu."],
        ["`ui/log_panel.py`, `ui/info_panel.py`", "The Log and Info tabs."],
        ["`ui/config_panel.py`", "The editable connector configuration table."],
        ["`core/serial_comm.py`", "SerialWorker thread: port, heartbeat, packet decoding into Qt signals."],
        ["`core/test_engine.py`", "Test state machine: parameters, netlist upload, scan start, verdict."],
        ["`core/packet_codec.py`, `core/crc16.py`", "Frame encoder, byte-wise decoder, CRC."],
        ["`core/netlist.py`", "Netlist load and save for JSON, XLSX and CSV; validation; connector mapping."],
        ["`core/pinmap.py`", "Reads, checks and writes connector_config.xlsx."],
        ["`core/result_model.py`", "Table model and colours for the results."],
        ["`core/report.py`", "PDF report with ReportLab, run on a worker thread."],
        ["`core/paths.py`", "Where files live when run from source or as an exe."],
        ["`core/data_types.py`", "Commands, responses, states, result and status types."],
    ], "GUI modules", weights=[34, 66])
    d.note("`core/profile.py`, the `ui/widgets` folder, `ui/golden_sample.py` "
           "and `ui/netlist_editor.py` are present in the source but not used "
           "by the running program. The last two are a netlist editor and a "
           "golden-sample wizard whose menu entries were removed.")
    d.h2("Threads and Signals")
    d.p("The window and the test engine run on the Qt main thread. "
        "SerialWorker is a QThread: it owns the port, sends queued packets, "
        "reads incoming bytes, feeds them to the decoder, and turns each "
        "complete packet into a Qt signal. The main thread never touches the "
        "port. Signals cross the thread boundary as queued connections, so "
        "slots run on the main thread.")
    d.figure(dia("data_flow.png"), "How a result reaches the screen", 14.0)
    d.h2("Test Engine")
    d.p("TestEngine keeps the state IDLE, UPLOADING, CALIBRATING, SCANNING or "
        "COMPLETE. start_test() sends the parameters, converts the netlist to "
        "compact JSON, splits it into chunks of 250 bytes, sends them, waits "
        "50 ms per chunk, and then sends the scan command for the chosen "
        "mode. When SCAN_DONE arrives it computes the verdict: PASS if no "
        "result failed, otherwise FAIL. A NACK during upload or scan returns "
        "the engine to IDLE. Auto-Scan sends AUTO_SCAN directly and always "
        "ends in PASS.")
    d.h2("From Channel to Connector Pin")
    d.p("core.pinmap reads connector_config.xlsx. core.netlist then uses it to "
        "fill each net's connector fields, and MainWindow keeps a table "
        "{channel: (connector, pin)}. The table turns the pair numbers of every "
        "result into the display pins and connector names shown in the views, "
        "and decides which pins each connector body draws.")
    d.figure(dia("mapping.png"), "From a netlist pin to a connector pin", 14.0)
    d.h2("Connector View Drawing")
    d.p("The Single view is one custom-painted widget. Connectors are stacked "
        "top to bottom on both sides, and a connector sits at the same height "
        "on both sides, so a wire between equal pin numbers is a straight "
        "line. A wire between different rows gets a vertical lane in the "
        "middle. Lane order is chosen to avoid wires lying on one another: "
        "wires that move down are ordered with the lowest start in the "
        "leftmost lane, wires that move up the other way, and neighbours are "
        "then swapped while that removes a crossing or an overlap. Where "
        "wires cross, the horizontal one is drawn with a small arch over the "
        "vertical one.")
    d.h2("Saved Files and Folders")
    d.p("core.paths keeps two roots: the bundle folder for read-only assets "
        "(themes, icons, the default connector configuration) and the data "
        "folder for files that must survive. Run from source, both are the "
        "gui folder. Run as a PyInstaller exe, the bundle is the temporary "
        "unpack folder and the data folder is HarnessTesterData beside the exe, "
        "or under LOCALAPPDATA if that cannot be written. A connector "
        "configuration saved by an earlier version is renamed from "
        "DB15-1, DB15-2 and DB9 to J1, J2 and J3 the first time it is read.")

    # ── 6 Build ─────────────────────────────────────────────────────────────────────────────────────────────────
    d.h1("Building and Testing")
    d.h2("Firmware")
    d.steps([
        "Open STM32CubeIDE and import the firmware folder as an existing project.",
        "Choose Project, Build Project. Use the Debug configuration. The output "
        "is `Debug/POC_HT.elf`.",
        "Flash it as described in the Flashing Procedure.",
    ])
    d.p("`HT_KEEP_TRACE` is a compiler symbol that stops the firmware "
        "from releasing the trace pins, for use in trace sessions. Do not set "
        "it for a delivered board.")
    d.h2("GUI from Source")
    d.code([
        "cd gui",
        "python -m venv venv",
        "venv\\Scripts\\activate",
        "pip install -r requirements.txt",
        "python main.py",
    ])
    d.h2("GUI Executable")
    d.p("Run `build.ps1` in the gui folder. It removes the old exe, clears the "
        "build folder and runs PyInstaller on `HarnessTester.spec`, which "
        "produces `dist/HarnessTester.exe`: one file, windowed, with the "
        "profiles, resources and the default connector configuration bundled. "
        "UPX packing is switched off because packed executables are flagged "
        "more often by security software. Copy the result to a dated name "
        "for delivery.")
    d.h2("Tests and Simulator")
    d.p("The folder `tests` holds pytest tests for the CRC and the packet "
        "codec. Run them with `python -m pytest tests` after installing the "
        "requirements. The folder `tools` holds `firmware_sim.py`, a stand-in "
        "for the board that answers on a virtual serial port, so the GUI can be "
        "developed without hardware. It needs a virtual port pair such as "
        "com0com, and its own README is out of date on the baud rate: use 115200.")

    # ── 7 Pin map ───────────────────────────────────────────────────────────────────────────────────────────────
    d.h1("Channel and Pin Map")
    d.p("The table lists, for each channel, the connector pin of the default "
        "configuration and the microcontroller pins. It is generated from the "
        "configuration file and checked against the firmware tables, so the "
        "two cannot differ.")
    d.table(["Channel", "Connector", "Pin", "Side A MCU", "Side B MCU"], pin_rows(),
            "Channel and pin map", center_cols=(0, 1, 2))
    d.p("Test pins that share a function with the board:")
    d.table(["Connector pin", "Side", "MCU pin", "Other use"], shared_pin_rows(),
            "Shared pins", center_cols=(1,))

    # ── 8 Limitations ───────────────────────────────────────────────────────────────────────────────────────────────
    d.h1("Known Limitations")
    d.p("These are properties of this version. They are listed so that they "
        "are not mistaken for faults, and so that a maintainer knows where "
        "to look.")
    d.table(["Area", "Limitation"], [
        ["Measurement", "Continuity only. Resistance values and the insulation "
         "command are fixed placeholders; calibrate is a 0.5 s blink that "
         "stores a fixed offset; SET_PARAM values are not used."],
        ["Cross continuity", "A listed pair is also treated as expected in "
         "reverse. A wire between different channel numbers therefore makes the "
         "reverse pair a missing connection and the verdict FAIL. The firmware "
         "has the same rule in its short-circuit scan."],
        ["Abort", "A scan runs inside the command handler and the receive "
         "buffer is read only between commands, so ABORT is processed after "
         "the scan in progress has ended. The flag it sets has no effect on "
         "that scan."],
        ["Debug text", "The firmware writes plain-text debug lines on the same "
         "serial port as the binary frames: [HT] BOOT and [HT] GPIO OK at "
         "start-up, and one [SCAN] line for every pair of a Continuity run. "
         "The GUI discards them while looking for the start byte 0xAA, so "
         "they do no harm, but a terminal program on the port shows them "
         "mixed with unreadable bytes."],
        ["Netlist", "Limits in section 3.6. Text beyond 4096 bytes is not "
         "stored and the upload never completes; the tester stays in "
         "UPLOADING, refuses scan commands, and must be power-cycled. The "
         "firmware keeps the last netlist, so a run with no netlist loaded "
         "may use an earlier one."],
        ["Pin numbering", "Side A and Side B share the numbers 1 to 37. A "
         "pin number outside 1 to 37 is skipped in a Continuity run and counted "
         "as a pass."],
        ["Auto-Scan", "The GUI shows PASS when the scan completes, even if "
         "stuck inputs were reported. A scan started with button B1 is not "
         "tracked by the GUI beyond showing the rows."],
        ["Faults", "The FAULT state, its LED pattern, the interlock code and "
         "the watchdog code are defined but never used. The independent "
         "watchdog is disabled. Stuck inputs are checked before a scan, not "
         "during it."],
        ["Status states", "The Info tab names the states 0 to 4 and shows "
         "other values in hexadecimal, so COMPLETE (5) appears as 0x05."],
        ["GUI", "The Harness ID in the Test Profile group is not stored. Two "
         "entries of the results context menu (Export Selected as PDF, Show "
         "Pin Detail) do nothing. Baud rates other than 115200 do not work "
         "with this firmware."],
        ["Reports", "The PDF report uses US Letter paper and the standard PDF "
         "fonts, and lists the results table only."],
        ["Board", "Test pins that share a function (section 7) can be driven by "
         "the other function. Applying voltage to a test pin can damage the "
         "microcontroller."],
    ], "Known limitations", weights=[20, 80])
    d.save(path)
    return d
